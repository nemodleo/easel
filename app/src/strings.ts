/** Every string widened to string (en is `as const`), so another language can give other words with the same keys and arguments */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends (...a: infer A) => infer R
      ? (...a: A) => Widen<R>
      : T extends readonly (infer U)[]
        ? readonly Widen<U>[]
        : T extends object
          ? { readonly [K in keyof T]: Widen<T[K]> }
          : T;
