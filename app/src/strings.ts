/* ---------- Which language ---------- */
export type Lang = "en" | "ko";
/** The languages the View menu offers, each named in itself */
export const LANGUAGES: readonly { id: Lang; name: string }[] = [
  { id: "en", name: "English" },
  { id: "ko", name: "한국어" },
];
/** localStorage, next to the other design-canvas:* keys: the language picked in the View menu */
export const LANG_KEY = "design-canvas:lang";
/** A language picked in the View menu wins; otherwise Korean for a ko browser (ko, ko-KR), English for anything else */
export function pickLang(saved: string | null | undefined, browser: string | null | undefined): Lang {
  if (saved === "en" || saved === "ko") return saved;
  return /^ko($|[-_])/i.test(browser ?? "") ? "ko" : "en";
}
function startLang(): Lang {
  if (typeof window === "undefined") return "en"; // tests and the server: English
  let saved: string | null = null;
  try {
    saved = localStorage.getItem(LANG_KEY);
  } catch {}
  return pickLang(saved, navigator.language);
}
/** The UI language, fixed for this page load (labels are read once, at module level, in several places) */
export const lang: Lang = startLang();
/** Remember a language and reload, so every label is read again in it */
export function setLang(next: Lang) {
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {}
  location.reload();
}

export const languages = { en, ko } as const satisfies Record<Lang, Strings>;
export const strings: Strings = languages[lang];
