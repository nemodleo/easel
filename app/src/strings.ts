/** A Korean particle after a word: 을/를, 이/가, 은/는, (으)로 by its last sound. Latin letters and digits are read the way
 * Korean speakers say them (file → 파일, 2 → 이); when the last character cannot be read, both forms show, as in 을(를) */
function particle(word: string, pair: "을/를" | "이/가" | "은/는" | "으로/로"): string {
  const ch = word.replace(/[\s>)"'”’\]]+$/, "").slice(-1);
  const c = ch.charCodeAt(0);
  let jong: number | null = null; // the final consonant's index, 0 for none, null when unknown
  if (c >= 0xac00 && c <= 0xd7a3) jong = (c - 0xac00) % 28;
  else if (/[0-9]/.test(ch)) jong = [21, 8, 0, 16, 0, 0, 1, 8, 8, 0][Number(ch)]; // 영 일 이 삼 사 오 육 칠 팔 구
  else if (/[lmn]/i.test(ch)) jong = /l/i.test(ch) ? 8 : /m/i.test(ch) ? 16 : 4;
  else if (/[a-z]/i.test(ch)) jong = 0;
  const [withFinal, without] = pair.split("/");
  if (jong == null) return pair === "으로/로" ? "(으)로" : `${withFinal}(${without})`;
  if (pair === "으로/로") return jong === 0 || jong === 8 ? "로" : "으로";
  return jong ? withFinal : without;
}
